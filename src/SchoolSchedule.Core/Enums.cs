namespace SchoolSchedule.Core.Models;

/// <summary>Смена, в которую учится класс.</summary>
public enum Shift
{
    Первая = 1,
    Вторая = 2,
}

/// <summary>День недели учебной сетки (без воскресенья).</summary>
public enum SchoolDay
{
    Понедельник = 1,
    Вторник = 2,
    Среда = 3,
    Четверг = 4,
    Пятница = 5,
    Суббота = 6,
}

/// <summary>Причина отсутствия учителя.</summary>
public enum AbsenceReason
{
    Болезнь = 0,
    Отпуск = 1,
    Командировка = 2,
    Другое = 3,
}

/// <summary>Итоговый статус подбора замены для конкретного урока на конкретную дату.</summary>
public enum SubstitutionStatus
{
    /// <summary>Найден учитель того же предмета.</summary>
    Замена = 0,
    /// <summary>Найден учитель другого предмета (запасной вариант).</summary>
    ЗаменаНеПоПрофилю = 1,
    /// <summary>Урок отменён.</summary>
    Отменено = 2,
    /// <summary>Класс объединён с другим на этот урок.</summary>
    Объединено = 3,
    /// <summary>Замена не найдена — требуется ручное решение администратора.</summary>
    НеНайдено = 4,
}
